-- Run in Supabase SQL Editor if anon INSERT is not already configured.
-- Existing order-management access and data are preserved.
begin;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  source text not null,
  customer_name text,
  customer_contact text not null,
  items_summary text not null,
  material text not null,
  delivery_service text not null,
  delivery_address text,
  total_price numeric not null default 0
);

alter table public.orders enable row level security;

grant insert (source, customer_name, customer_contact, items_summary, material,
              delivery_service, delivery_address, total_price)
on public.orders to anon;

drop policy if exists website_order_insert on public.orders;
create policy website_order_insert on public.orders
for insert to anon
with check (
  source = 'website'
  and char_length(coalesce(customer_name, '')) <= 120
  and char_length(btrim(customer_contact)) between 1 and 254
  and char_length(items_summary) between 1 and 2500
  and material in ('PETG', 'PLA', 'ABS')
  and delivery_service = 'cdek'
  and char_length(coalesce(delivery_address, '')) <= 1000
  and total_price between 0 and 2147483647
);

commit;
